/**
 * Selects which agents to activate based on project type and channels.
 * This is a rule-based pre-selection; the LLM orchestrator refines it further.
 */
export function selectAgents(answers: DiscoveryAnswers): AgentSelection[] {
  const selected: AgentSelection[] = [];
  const type = answers.project_type.toLowerCase();
  const channels = (answers.channels || []).map(c => c.toLowerCase());
  const goal = answers.primary_goal.toLowerCase();

  // ─── Always include ────────────────────────────────────────
  selected.push({
    id: "product_manager",
    domain: "tech/product",
    reason: "Every project needs a product spec and feature backlog"
  });

  // ─── Tech agents based on channels ─────────────────────────
  if (channels.some(c => ["web", "website", "landing page"].includes(c)) ||
      ["web app", "landing page", "blog", "saas", "ecommerce"].some(t => type.includes(t))) {
    selected.push(
      { id: "ux_designer", domain: "tech/design", reason: "Web requires UX flows" },
      { id: "ui_designer", domain: "tech/design", reason: "Visual design for web" },
      { id: "web_frontend_engineer", domain: "tech/frontend", reason: "Build the web UI" },
      { id: "frontend_performance_engineer", domain: "tech/frontend", reason: "Core Web Vitals" },
      { id: "accessibility_engineer", domain: "tech/frontend", reason: "WCAG compliance" }
    );
  }

  if (channels.some(c => c.includes("ios"))) {
    selected.push({ id: "ios_engineer", domain: "tech/mobile", reason: "iOS app required" });
  }

  if (channels.some(c => c.includes("android"))) {
    selected.push({ id: "android_engineer", domain: "tech/mobile", reason: "Android app required" });
  }

  if (channels.some(c => c.includes("ios") && c.includes("android")) ||
      type.includes("mobile app")) {
    // Prefer cross-platform if both iOS and Android needed
    selected.push({
      id: "cross_platform_engineer",
      domain: "tech/mobile",
      reason: "Both iOS and Android required — consider React Native"
    });
  }

  if (["web app", "saas", "ecommerce", "mobile app"].some(t => type.includes(t))) {
    selected.push(
      { id: "backend_engineer", domain: "tech/backend", reason: "App requires server-side logic" },
      { id: "api_designer", domain: "tech/backend", reason: "API contract before dev starts" },
      { id: "database_engineer", domain: "tech/data", reason: "Data model and schema" },
      { id: "security_engineer", domain: "tech/security", reason: "Auth and security audit" },
      { id: "devops_engineer", domain: "tech/infra", reason: "Deployment and CI/CD" }
    );
  }

  if (type.includes("3d") || answers.design_style?.toLowerCase().includes("3d")) {
    selected.push(
      { id: "3d_designer", domain: "tech/creative", reason: "3D design required" },
      { id: "webgl_engineer", domain: "tech/creative", reason: "WebGL implementation" }
    );
  }

  // QA is always needed for product builds
  if (!["email campaign", "blog post"].some(t => type.includes(t))) {
    selected.push(
      { id: "qa_engineer", domain: "tech/qa", reason: "Feature testing and sign-off" },
      { id: "test_automation_engineer", domain: "tech/qa", reason: "Automated test suite" }
    );
  }

  // ─── Marketing agents ──────────────────────────────────────
  if (channels.some(c => c.includes("email")) || type.includes("email")) {
    selected.push(
      { id: "email_strategist", domain: "marketing/email", reason: "Email program design" },
      { id: "email_copywriter", domain: "marketing/email", reason: "Email copy" },
      { id: "email_designer", domain: "marketing/email", reason: "Email templates" },
      { id: "email_platform_builder", domain: "marketing/email", reason: "ESP setup" }
    );
  }

  if (channels.some(c => c.includes("social"))) {
    selected.push(
      { id: "social_media_marketer", domain: "marketing/social", reason: "Social content strategy" },
      { id: "marketing_designer", domain: "marketing/design", reason: "Social creatives" }
    );
  }

  if (channels.some(c => ["paid", "ads", "ppc"].some(k => c.includes(k)))) {
    selected.push(
      { id: "performance_marketer", domain: "marketing/paid", reason: "Paid acquisition" },
      { id: "sem_specialist", domain: "marketing/paid", reason: "Google Ads" }
    );
  }

  if (type.includes("blog") || goal.includes("seo") || goal.includes("organic")) {
    selected.push(
      { id: "seo_specialist", domain: "marketing/seo", reason: "SEO optimisation" },
      { id: "content_strategist", domain: "marketing/content", reason: "Content planning" },
      { id: "editorial_writer", domain: "marketing/content", reason: "Blog post writing" }
    );
  }

  if (goal.includes("launch") || goal.includes("growth") || goal.includes("signup")) {
    selected.push(
      { id: "marketing_strategist", domain: "marketing/strategy", reason: "GTM plan" },
      { id: "growth_marketer", domain: "marketing/growth", reason: "Growth loops and experiments" },
      { id: "marketing_analytics", domain: "marketing/analytics", reason: "Measurement and attribution" }
    );
  }

  // Deduplicate by id
  const seen = new Set<string>();
  return selected.filter(a => {
    if (seen.has(a.id)) return false;
    seen.add(a.id);
    return true;
  });
}

/**
 * Saves the PRD to the runs/prds directory.
 */
export function savePRD(
  projectId: string,
  prdContent: string,
  outputDir: string = "./runs/prds"
): string {
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }
  const filename = `${projectId}-prd.md`;
  const filepath = path.join(outputDir, filename);
  fs.writeFileSync(filepath, prdContent, "utf-8");
  return filepath;
}
