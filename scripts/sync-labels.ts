// ─── GitHub API ───────────────────────────────────────────────────────────────

async function getRepoInfo(): Promise<{ owner: string; repo: string } | null> {
  try {
    const { execSync } = require("child_process");
    const remote = execSync("git remote get-url origin", { encoding: "utf-8" }).trim();
    // Parse github.com/owner/repo
    const match = remote.match(/github\.com[/:](.+?)\/(.+?)(?:\.git)?$/);
    if (match) return { owner: match[1], repo: match[2] };
  } catch {}
  return null;
}

async function syncLabels(
  token: string,
  owner: string,
  repo: string,
  dryRun: boolean
): Promise<void> {
  const baseUrl = `https://api.github.com/repos/${owner}/${repo}/labels`;
  const headers = {
    Authorization: `token ${token}`,
    Accept: "application/vnd.github.v3+json",
    "Content-Type": "application/json",
  };

  // Get existing labels
  const resp = await fetch(`${baseUrl}?per_page=100`, { headers });
  if (!resp.ok) {
    throw new Error(`Failed to fetch labels: ${resp.status} ${resp.statusText}`);
  }
  const existing = (await resp.json()) as Array<{ name: string; color: string; description: string }>;
  const existingMap = new Map(existing.map((l) => [l.name, l]));

  let created = 0;
  let updated = 0;
  let unchanged = 0;

  for (const label of LABELS) {
    const current = existingMap.get(label.name);

    if (!current) {
      // Create
      if (dryRun) {
        console.log(`  + CREATE: ${label.name} (#${label.color})`);
      } else {
        const createResp = await fetch(baseUrl, {
          method: "POST",
          headers,
          body: JSON.stringify(label),
        });
        if (createResp.ok) {
          console.log(`  ✅ Created: ${label.name}`);
        } else {
          console.log(`  ❌ Failed to create: ${label.name} — ${createResp.status}`);
        }
      }
      created++;
    } else if (
      current.color !== label.color ||
      current.description !== label.description
    ) {
      // Update
      if (dryRun) {
        console.log(`  ~ UPDATE: ${label.name}`);
      } else {
        const updateResp = await fetch(
          `${baseUrl}/${encodeURIComponent(label.name)}`,
          {
            method: "PATCH",
            headers,
            body: JSON.stringify({
              color: label.color,
              description: label.description,
            }),
          }
        );
        if (updateResp.ok) {
          console.log(`  ✏️  Updated: ${label.name}`);
        } else {
          console.log(`  ❌ Failed to update: ${label.name} — ${updateResp.status}`);
        }
      }
      updated++;
    } else {
      unchanged++;
    }
  }

  console.log();
  console.log(
    `Summary: ${created} created, ${updated} updated, ${unchanged} unchanged`
  );
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const dryRun = args.includes("--dry-run");

  const token = process.env['GITHUB_TOKEN'];
  if (!token) {
    console.log("Set GITHUB_TOKEN environment variable to sync labels.");
    console.log("Usage: GITHUB_TOKEN=ghp_xxx npm run sync:labels\n");

    // Still show what labels would be synced
    console.log(`📋 ${LABELS.length} labels defined:\n`);
    for (const label of LABELS) {
      console.log(`  #${label.color} ${label.name} — ${label.description}`);
    }
    process.exit(0);
  }

  const repoInfo = await getRepoInfo();
  if (!repoInfo) {
    console.error("Could not determine GitHub repo from git remote.");
    process.exit(1);
  }

  console.log(`🏷️  Syncing labels to ${repoInfo.owner}/${repoInfo.repo}${dryRun ? " (DRY RUN)" : ""}\n`);
  await syncLabels(token, repoInfo.owner, repoInfo.repo, dryRun);
}

main().catch((e) => {
  console.error(`Fatal: ${e.message}`);
  process.exit(1);
});
